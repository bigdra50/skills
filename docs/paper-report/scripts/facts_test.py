def test_build_sh_は値がずれていたら_tectonic_の前に止まる(tmp_path, capsys):
    report = tmp_path / "r"
    report.mkdir()
    make_report(report, {"a": {"x": "1"}}, tex="\\fact{x}\n")
    invoke(capsys, "update", str(report))
    write_data(report, "a", {"x": "2"})
    result = subprocess.run(
        ["bash", str(HERE / "build.sh"), "paper.tex", str(tmp_path / "pages")],
        cwd=report,
        capture_output=True,
        text=True,
        check=False,
    )
    out = result.stdout + result.stderr
    assert result.returncode != 0
    assert "changed x" in out and "facts.py update" in out
    assert not (report / "paper.pdf").exists()


def test_build_sh_の_no_facts_は照合を飛ばす(tmp_path, capsys):
    report = tmp_path / "r"
    report.mkdir()
    make_report(report, {"a": {"x": "1"}}, tex="\\fact{x}\n")
    invoke(capsys, "update", str(report))
    write_data(report, "a", {"x": "2"})
    result = subprocess.run(
        ["bash", str(HERE / "build.sh"), "--no-facts", "paper.tex", str(tmp_path / "pages")],
        cwd=report,
        capture_output=True,
        text=True,
        check=False,
    )
    out = result.stdout + result.stderr
    assert "facts: skipped (--no-facts)" in out
    assert "changed x" not in out


needs_tectonic = pytest.mark.skipif(
    shutil.which("tectonic") is None or sys.platform != "darwin",
    reason="テンプレートのビルドには tectonic と macOS のヒラギノが要る",
)

BODY = r"""\begin{document}
\section{遅れは \fact{lag} ms}
本文の遅れは \fact{lag} ms で、差は \fact{share} だった。
\begin{table}[h]
\caption{肩の遅れは \fact{rate} ms}
\begin{tabular}{lS[table-format=3.1]}
\toprule
{関節} & {遅れ} \\
\midrule
肩 & \fact{rate} \\
肘 & 12.5 \\
\bottomrule
\end{tabular}
\end{table}
\begin{tikzpicture}
\begin{axis}[width=5cm,height=4cm]
\addplot coordinates {(0,\fact{rate}) (1,12.5)};
\end{axis}
\end{tikzpicture}
\end{document}
"""


def preamble() -> str:
    text = TEMPLATE.read_text(encoding="utf-8")
    return text[: text.index("\\begin{document}")]


@needs_tectonic
def test_テンプレートの前置きで_fact_が本文と見出しと表題と_S_列とグラフに入る(tmp_path, capsys):
    report = make_report(tmp_path, {"a": {"lag": "267〜333", "share": "12 %", "rate": "100.5"}}, tex=preamble() + BODY)
    assert invoke(capsys, "update", str(report))[0] == 0
    result = subprocess.run(
        ["tectonic", "-X", "compile", "paper.tex"], cwd=report, capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr[-3000:]
    if shutil.which("pdftotext"):
        text = subprocess.run(
            ["pdftotext", "paper.pdf", "-"], cwd=report, capture_output=True, text=True, check=False
        ).stdout
        assert "267" in text and "333" in text and "100.5" in text and "%" in text


@needs_tectonic
def test_facts_tex_に無いキーを引用すると_ビルドが落ちる(tmp_path, capsys):
    tex = preamble() + "\\begin{document}\n遅れは \\fact{nope} ms。\n\\end{document}\n"
    report = make_report(tmp_path, {"a": {"x": "1"}}, tex=tex)
    invoke(capsys, "update", str(report))
    result = subprocess.run(
        ["tectonic", "-X", "compile", "paper.tex"], cwd=report, capture_output=True, text=True, check=False
    )
    assert result.returncode != 0
    assert "Undefined fact" in result.stdout + result.stderr
