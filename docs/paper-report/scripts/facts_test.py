def test_必要なデータが無いコマンドは飛ばし_書いてある値を残す(tmp_path, capsys):
    report = make_report(tmp_path, {"a": {"x": "1"}, "b": {"y": "2"}}, tex="\\fact{x} \\fact{y}\n")
