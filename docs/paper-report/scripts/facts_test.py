def test_check_は変わった値と_それを引用する行を示して落ち_facts_tex_は書き換えない(tmp_path, capsys):
    report = make_report(tmp_path, {"a": {"lag-up": "267〜333"}}, tex="前置き\n遅れは \\fact{lag-up} ms だった。\n")
    invoke(capsys, "update", str(report))
    before = (report / "facts.tex").read_text(encoding="utf-8")
    write_data(report, "a", {"lag-up": "300"})
    code, out = invoke(capsys, "check", str(report))
    assert code == 1
    assert "lag-up" in out and "267〜333" in out and "300" in out
    assert "paper.tex:2" in out
    assert (report / "facts.tex").read_text(encoding="utf-8") == before


